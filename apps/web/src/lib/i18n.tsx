type LanguageContextValue = {
  lang: Lang;
  setLang: (lang: Lang) => void;
};

const LanguageContext = createContext<LanguageContextValue | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");

  useEffect(() => {
    // Reads the persisted choice once after mount, matching SSR's "en"
    // default on first paint to avoid a hydration mismatch.
    try {
      const stored = window.localStorage.getItem(STORAGE_KEY);
      // eslint-disable-next-line react-hooks/set-state-in-effect
      if (isLang(stored)) setLangState(stored);
    } catch {
      // localStorage unavailable — stay on default "en"
    }
  }, []);

  // Arabic runs right to left, so the document itself has to be told: the
  // layout renders on the server, where the stored choice isn't readable yet.
  useEffect(() => {
    const locale = localeFor(lang);
    document.documentElement.lang = locale.code;
    document.documentElement.dir = locale.dir;
  }, [lang]);

  const setLang = (next: Lang) => {
    setLangState(next);
    try {
      window.localStorage.setItem(STORAGE_KEY, next);
    } catch {
      // ignore write failures (private browsing, etc.)
    }
  };

  const value = useMemo(() => ({ lang, setLang }), [lang]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

function translate(lang: Lang, key: string, vars?: Record<string, string | number>) {
  const dict = dictionaries[lang] ?? dictionaries.en;
  let str = dict[key] ?? dictionaries.en[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      str = str.replaceAll(`{{${name}}}`, String(value));
    }
  }
  return str;
}

export function useT() {
  const ctx = useContext(LanguageContext);
  const lang = ctx?.lang ?? "en";
  return (key: string, vars?: Record<string, string | number>) => translate(lang, key, vars);
}

export function useLanguage() {
  const ctx = useContext(LanguageContext);
  if (!ctx) throw new Error("useLanguage must be used within a LanguageProvider");
  return ctx;
}
